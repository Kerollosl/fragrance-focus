'use strict';
document.getElementById('run-checks').addEventListener('click',async()=>{
  const results=[];const check=(name,passed)=>results.push({name,passed:!!passed});
  const F=FragranceFocus;const data=F.extract(document,'https://www.fragrantica.com/');
  const settle=()=>new Promise(resolve=>setTimeout(resolve,250));
  const title=document.querySelector('.ff-product h1');
  const bottle=document.querySelector('.ff-product img[itemprop="image"]');
  const firstNote=document.querySelector('.pyramid-note-link');
  check('Name and brand extracted',data.name==='Khamrah'&&data.brand==='Lattafa Perfumes');
  check('Rating is source data',data.rating===4.2&&data.ratingCount===31330);
  check('Eight relative accords',data.accords.length===8&&data.accords[1].strength===82.2837);
  check('All thirteen notes retained',data.notes.reduce((sum,g)=>sum+g.notes.length,0)===13);
  check('Native title remains visible',title.getBoundingClientRect().height>0);
  check('Native header stays visible',getComputedStyle(document.querySelector('#app>header')).display!=='none');
  check('Native font is retained',getComputedStyle(title).fontFamily===getComputedStyle(document.body).fontFamily);
  check('Native colorful accords retained',getComputedStyle(document.querySelector('#fixture-accords div[style]')).backgroundColor==='rgb(238, 54, 59)');
  check('Photographic pyramid stays vertical',getComputedStyle(firstNote).flexDirection==='column'&&firstNote.querySelector('img'));
  check('No replacement hero or branding',!document.querySelector('.ff-overview,.ff-wordmark,.ff-facts'));
  check('Duplicate injection keeps one navigator',document.querySelectorAll('#ff-reader').length===1);
  check('Visual reading order includes keyboard flow',getComputedStyle(document.querySelector('.ff-product')).getPropertyValue('reading-flow')==='flex-visual');
  check('Reactive empty wrappers stay displayed',getComputedStyle(document.querySelector('#fixture-performance')).display!=='none');
  check('Ad and offer slots collapsed',[...document.querySelectorAll('.sliding-ad-container,.perfume-offer-box')].every(el=>getComputedStyle(el).display==='none'));
  const sourceButton=document.querySelector('#fixture-note-toggle');sourceButton.click();
  check('Native note listener preserved',sourceButton.textContent==='Hide votes');sourceButton.click();
  const vote=document.querySelector('#fixture-rating .cursor-pointer');vote.click();
  check('Native voting listener preserved',document.querySelector('#fixture-rating .fixture-vote-items').dataset.clicked==='love');
  document.querySelector('.ff-nav [data-jump="notes"]').click();
  check('Section jumps keep native button tabbable',sourceButton.tabIndex===0);
  const rating=document.querySelector('[itemprop="ratingValue"]');rating.textContent='4.21';await settle();
  check('Live source updates preserve native nodes',rating.textContent==='4.21'&&title===document.querySelector('.ff-product h1')&&bottle===document.querySelector('.ff-product img[itemprop="image"]'));
  rating.textContent='4.20';await settle();
  const performance=document.querySelector('#fixture-performance');
  performance.innerHTML='<div class="tw-rating-card"><span class="tw-rating-card-label">Longevity</span><div class="cursor-pointer"><span>long lasting</span><span>120</span></div></div>';
  await settle();
  check('Late native performance gets a jump target',document.querySelector('.ff-nav [data-jump="performance"]')&&performance.getBoundingClientRect().height>0);
  performance.replaceChildren();await settle();
  check('Empty performance does not get a dead jump',!document.querySelector('.ff-nav [data-jump="performance"]'));
  document.querySelector('#ff-layout-toggle').click();
  check('Original spacing restores without replacing content',!document.documentElement.classList.contains('ff-reader-on')&&getComputedStyle(title).display!=='none'&&firstNote===document.querySelector('.pyramid-note-link'));
  check('Ad removal survives spacing switch',getComputedStyle(document.querySelector('.perfume-offer-box')).display==='none');
  document.querySelector('#ff-layout-toggle').click();
  check('No horizontal page overflow',document.documentElement.scrollWidth<=innerWidth);
  const result=document.getElementById('check-results');result.textContent=results.map(r=>`${r.passed?'PASS':'FAIL'} ${r.name}`).join('\n');result.style.whiteSpace='pre-wrap';result.dataset.passed=String(results.filter(r=>r.passed).length);result.dataset.total=String(results.length);
});
